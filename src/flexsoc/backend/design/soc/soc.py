SUPPORTED_HOSTS = {"ibex", "uart"}
SUPPORTED_FABRICS = {"tlul"}
HOST_IPS = {"ibex", "ibex_top"}
KNOWN_BASES = {
    "uart": 0x80000000,
    "uart_master": 0x80000000,
    "gpio": 0x80040000,
    "rv_timer": 0x80060000,
    "spi_host": 0x80080000,
}
SRAM_BASE = 0x00100000
SRAM_SIZE = 128 * 1024
IBEX_RESET_VECTOR_OFFSET = 0x80


@dataclass(frozen=True, slots=True)
class SoCDevice:
    """One memory-mapped endpoint in the resolved SoC plan."""

    name: str
    base: int
    size: int = 0x1000
    builtin: bool = False

    @property
    def base_hex(self) -> str:
        return f"0x{self.base:08X}"

    @property
    def size_hex(self) -> str:
        return f"0x{self.size:08X}"

    def to_dict(self) -> dict[str, object]:
        return {
            "name": self.name,
            "base": self.base_hex,
            "size": self.size_hex,
            "builtin": self.builtin,
        }


@dataclass(frozen=True, slots=True)
class SoCPlan:
    """Single source of truth for one resolved SoC composition."""

    host: str
    fabric: str
    devices: tuple[SoCDevice, ...]

    @property
    def external_devices(self) -> tuple[SoCDevice, ...]:
        return tuple(device for device in self.devices if not device.builtin)

    def device(self, name: str) -> SoCDevice:
        matches = tuple(device for device in self.devices if device.name == name)
        if len(matches) != 1:
            raise ValueError(f"expected exactly one SoC device named {name!r}, found {len(matches)}")
        return matches[0]

    @property
    def ibex_boot_addr(self) -> int:
        if self.host != "ibex":
            raise ValueError(f"host {self.host!r} has no Ibex boot address")
        return self.device("sram").base

    @property
    def reset_pc(self) -> int:
        if self.host != "ibex":
            raise ValueError(f"host {self.host!r} has no CPU reset PC")
        return self.ibex_boot_addr + IBEX_RESET_VECTOR_OFFSET

    def to_dict(self) -> dict[str, object]:
        return {
            "schema": 1,
            "host": self.host,
            "fabric": self.fabric,
            "devices": [device.to_dict() for device in self.devices],
        }


@dataclass(frozen=True, slots=True)
class RtlSourceSet:
    """Deterministic native FlexSoC RTL source manifest."""

    entries: tuple[str, ...]

    @classmethod
    def from_entries(cls, entries: list[str] | tuple[str, ...]) -> "RtlSourceSet":
        ordered: list[str] = []
        seen: set[str] = set()
        for raw in entries:
            entry = str(raw).strip()
            if not entry or entry.startswith("#") or entry in seen:
                continue
            seen.add(entry)
            ordered.append(entry)
        return cls(tuple(ordered))

    def write(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        body = "\n".join(self.entries)
        path.write_text(
            "# Auto-generated by FlexSoC native source resolver.\n"
            + body
            + ("\n" if body else ""),
            encoding="utf-8",
        )
        return path

@dataclass(slots=True)
class TlulFabric:
    """Generate the concrete TL-UL fabric with the vendored OpenTitan tlgen."""

    project_root: Path
    runner: ToolRunner

    @staticmethod
    def host_name(host: str) -> str:
        return "uart_host" if host == "uart" else "ibex"

    @staticmethod
    def host_node(name: str) -> dict[str, Any]:
        return {
            "name": name,
            "type": "host",
            "clock": "clk_i",
            "reset": "rst_ni",
            "xbar": False,
            "pipeline": False,
        }

    @staticmethod
    def device_node(device: SoCDevice) -> dict[str, Any]:
        return {
            "name": device.name,
            "type": "device",
            "clock": "clk_i",
            "reset": "rst_ni",
            "xbar": False,
            "addr_range": [{"base_addr": device.base_hex, "size_byte": device.size_hex}],
        }

    def payload(self, plan: SoCPlan) -> dict[str, Any]:
        host = self.host_name(plan.host)
        return {
            "name": "main",
            "type": "xbar",
            "clock": "clk_i",
            "clock_connections": {"clk_i": "main"},
            "reset": "rst_ni",
            "reset_connections": {"rst_ni": "main"},
            "nodes": [self.host_node(host), *(self.device_node(device) for device in plan.devices)],
            "connections": {host: [device.name for device in plan.devices]},
        }

    def generate(self, plan: SoCPlan, run_dir: Path, log: Path, *, on: str = "local") -> object:
        config = run_dir / "soc" / "xbar.hjson"
        SocFlow.write_json(config, self.payload(plan))
        outputs = (
            run_dir / "rtl" / "autogen" / "tl_main_pkg.sv",
            run_dir / "rtl" / "autogen" / "xbar_main.sv",
        )
        argv = (
            sys.executable,
            str(self.project_root / "src" / "util" / "tlgen.py"),
            "-t", str(config),
            "-o", str(run_dir),
        )
        return self.runner.run(
            CommandRequest(argv, self.project_root, {}, log, (config,), outputs), on=on
        )


@dataclass(slots=True)
class SoCDv:
    """Generate the shared SoC testbench around workspace-owned functional tests."""

    context: BackendContext

    @property
    def paths(self):
        return self.context.paths

    def validate(self, test: str) -> Path:
        test_dir = self.paths.tests / test
        required = tuple(test_dir / name for name in ("config.regs", "data_in.vec", "data_out.vec"))
        missing = [path for path in required if not path.is_file()]
        if missing:
            raise FileNotFoundError(
                f"functional test {test!r} is incomplete: " + ", ".join(map(str, missing))
            )
        return test_dir

    def generate(self, plan: SoCPlan) -> tuple[Path, ...]:
        """Generate only generic TB infrastructure; test collateral stays in the workspace."""

        from flexsoc.backend.dv.tb.common import TestEventSource
        from flexsoc.backend.dv.tb.sv import SystemVerilogTestbench, TestbenchConfig

        test = str(self.context.values.get("TEST_NAME", "smoke")).strip() or "smoke"
        test_dir = self.paths.tests / test
        parameters: tuple[tuple[str, str], ...] = ()
        if test_dir.is_dir() and (test_dir / "sw").is_dir():
            if plan.host != "ibex":
                raise ValueError("software functional tests currently require the ibex SoC host")
            plan.device("sram")
            vmem = test_dir / "sw" / "build" / "main.vmem"
            parameters = (("SramInitFile", f'"{vmem.as_posix()}"'),)

        period = max(1, int(float(self.context.values.get("CLK_PERIOD", "10"))))
        event_source = None
        if plan.host == "ibex":
            event_source = TestEventSource(
                "clk_i",
                "u_dut.sram_data_req && u_dut.sram_data_we && &u_dut.sram_data_wmask",
                "u_dut.sram_data_wdata",
            )
        config = TestbenchConfig(
            top="soc", rtldir=self.paths.rtl, simdir=self.paths.sim,
            syndir=self.paths.syn, prims=(), clk_period_ns=period,
            compiler="verilator", interface=plan.fabric, output=self.paths.tb / "sv",
            dut_parameters=parameters,
            event_source=event_source,
        )
        return tuple(SystemVerilogTestbench().setup(config, clocks=self.context.clocks))


class SocFlow:
    """Resolve and generate one SoC composition for the current backend context."""

    def __init__(self, context: BackendContext, runner: ToolRunner | None = None):
        self.context = context
        self.runner = runner or ToolRunner(project_root=context.project_root)
        self.fabric = TlulFabric(context.project_root, self.runner)
        self.dv = SoCDv(context)
        self.software = SoCSoftware(context, self.runner)

    @property
    def paths(self):
        return self.context.paths

    @property
    def values(self):
        return self.context.values

    def run_target(self, target, *, on: str = "local"):
        """Execute the single public SoC target."""

        if target.action != "soc":
            raise ValueError(f"unsupported SoC action: {target.action!r}")
        action = str(self.values.get("SOC_ACTION", "generate")).strip().lower()
        if action == "show":
            return self.show()
        if action == "build":
            return self.build(on=on)
        if action == "simulate":
            return self.simulate(on=on)
        if action == "view":
            return self.view(on=on)
        if action != "generate":
            raise ValueError(
                f"unsupported SoC option {action!r}; expected generate, build, simulate, view, or show"
            )
        return self.generate(on=on)

    def prepare_run(self) -> tuple[Path, ...]:
        """Create canonical SoC run directories and merge staged IP RTL filelists."""

        run = self.paths.run
        for path in (
            run / "ips", self.paths.rtl, self.paths.logs, self.paths.doc,
            self.paths.tb, self.paths.sim, self.paths.tests, self.paths.model, run / "soc",
        ):
            path.mkdir(parents=True, exist_ok=True)
        ips = self.loaded_ip_dirs()
        (run / "ips" / "loaded_ips.txt").write_text(
            "".join(f"{ip.name}\n" for ip in ips), encoding="utf-8"
        )
        sources = self.merged_rtl_sources(ips) if ips else ()
        (run / "rtl" / "rtl_ip.f").write_text(
            "\n".join(sources) + ("\n" if sources else ""), encoding="utf-8"
        )
        (run / "rtl" / "rtl_list.f").unlink(missing_ok=True)
        return ips

    def loaded_ip_dirs(self) -> tuple[Path, ...]:
        ips = self.paths.run / "ips"
        if not ips.is_dir():
            return ()
        return tuple(sorted(path for path in ips.iterdir() if path.is_dir()))

    def resolve_plan(self) -> SoCPlan:
        """Resolve host infrastructure plus explicitly staged reusable IPs."""

        host = self.normalize_host(str(self.values.get("HOST", "ibex")))
        fabric = self.normalize_fabric(str(self.values.get("FABRIC", "tlul")))
        loaded = tuple(path.name for path in self.loaded_ip_dirs())

        devices = list(self.builtin_devices(host))
        used_names = {device.name for device in devices}
        used_bases = {device.base for device in devices}
        next_base = 0x800A0000

        for name in loaded:
            if name in HOST_IPS or name in used_names:
                continue
            base = KNOWN_BASES.get(name)
            if base is None:
                while next_base in used_bases:
                    next_base += 0x00020000
                base = next_base
                next_base += 0x00020000
            if base in used_bases:
                raise ValueError(f"duplicate SoC base address 0x{base:08X} for {name}")
            devices.append(SoCDevice(name, base))
            used_names.add(name)
            used_bases.add(base)

        return SoCPlan(host, fabric, tuple(devices))

    @staticmethod
    def normalize_host(host: str) -> str:
        host = host.strip().lower()
        if host not in SUPPORTED_HOSTS:
            raise ValueError(f"unsupported SoC host {host!r}; expected one of: {', '.join(sorted(SUPPORTED_HOSTS))}")
        return host

    @staticmethod
    def normalize_fabric(fabric: str) -> str:
        fabric = fabric.strip().lower()
        if fabric not in SUPPORTED_FABRICS:
            raise ValueError("unsupported SoC fabric {!r}; currently supported: tlul".format(fabric))
        return fabric

    @staticmethod
    def builtin_devices(host: str) -> tuple[SoCDevice, ...]:
        """Return only infrastructure intrinsically required by a host."""

        if host == "ibex":
            return (SoCDevice("sram", SRAM_BASE, SRAM_SIZE, True),)
        if host == "uart":
            return ()
        raise ValueError(f"unsupported SoC host {host!r}")

    def write_plan(self, plan: SoCPlan) -> Path:
        return self.write_json(self.paths.run / "soc" / "plan.json", plan.to_dict())

    def show(self, *, as_json: bool = False) -> int:
        """Print the stored plan, or the currently resolved plan when not generated yet."""

        payload = self.resolve_plan().to_dict()
        print(json.dumps(payload, indent=None if as_json else 2, sort_keys=True))
        return 0

    def generate(self, *, on: str = "local") -> object:
        """Generate the complete hardware composition for the current SoC plan."""

        self.prepare_run()
        plan = self.resolve_plan()
        self.write_plan(plan)
        result = self.fabric.generate(plan, self.paths.run, self.paths.logs / "soc" / "tlgen.log", on=on)
        if getattr(result, "returncode", 0):
            return result
        self.generate_top(plan)
        self.write_soc_rtl_filelist(plan)
        self.write_native_rtl_filelist(plan, on=on)
        return self.paths.run / "soc" / "plan.json"

    def vendor_roots(self) -> tuple[Path, Path]:
        """Return the pinned vendor roots required by the current M0 SoC."""

        roots = (
            self.context.project_root / "vendor" / "lowrisc_ibex",
            self.context.project_root / "vendor" / "lowrisc_ip",
        )
        missing = tuple(path for path in roots if not path.is_dir())
        if missing:
            names = ", ".join(path.name for path in missing)
            raise FileNotFoundError(
                f"missing vendored SoC dependencies: {names}; fetch the pinned vendor inputs first"
            )
        return roots


    def native_rtl_inputs(self) -> tuple[Path, ...]:
        """Return concrete RTL source inputs referenced by the native rtl.f."""

        filelist = self.paths.rtl / "rtl.f"
        if not filelist.is_file():
            raise FileNotFoundError(f"missing native SoC RTL filelist: {filelist}")

        inputs: list[Path] = [filelist]
        for raw in filelist.read_text(encoding="utf-8").splitlines():
            entry = raw.strip()
            if not entry or entry.startswith("+"):
                continue
            path = Path(entry)
            resolved = path if path.is_absolute() else (self.paths.run / path).resolve()
            if not resolved.is_file():
                raise FileNotFoundError(f"native rtl.f references missing source: {resolved}")
            inputs.append(resolved)

        return tuple(dict.fromkeys(inputs))

    def native_verilator_lint(self, *, on: str = "local") -> object:
        """Elaborate/lint the generated SoC directly from the native rtl.f."""

        filelist = self.paths.rtl / "rtl.f"
        argv = (
            str(self.values.get("VERILATOR", "verilator")),
            "--lint-only",
            "--sv",
            "--timing",
            "-Wall",
            "-Wno-fatal",
            "-f",
            str(filelist),
            "--top-module",
            "soc",
        )
        return self.runner.run(
            CommandRequest(
                argv,
                self.paths.run,
                {},
                self.paths.logs / "soc" / "build.log",
                inputs=self.native_rtl_inputs(),
            ),
            on=on,
        )

    def native_verilator_simulator(self, *, on: str = "local") -> tuple[object, Path]:
        """Build the generated SoC functional testbench directly with Verilator."""

        filelist = self.paths.rtl / "rtl.f"
        sv_dir = self.paths.tb / "sv"
        source = sv_dir / "soc_tb.sv"
        if not source.is_file():
            raise FileNotFoundError(f"generated SoC testbench not found: {source}")

        build_dir = self.paths.sim / "verilator"
        shutil.rmtree(build_dir, ignore_errors=True)
        build_dir.parent.mkdir(parents=True, exist_ok=True)
        simulator = build_dir / "Vsoc_tb"

        tb_inputs = tuple(sorted(path for path in sv_dir.rglob("*") if path.is_file()))
        inputs = tuple(dict.fromkeys((*self.native_rtl_inputs(), *tb_inputs)))

        argv = (
            str(self.values.get("VERILATOR", "verilator")),
            "-Wall",
            "-Wno-fatal",
            "--binary",
            "--timing",
            "--Mdir",
            str(build_dir),
            "--trace-fst",
            "--trace-structs",
            f"-I{sv_dir}",
            f"-I{self.paths.rtl}",
            "-f",
            str(filelist),
            str(source),
            "--top-module",
            "soc_tb",
        )
        result = self.runner.run(
            CommandRequest(
                argv,
                self.paths.run,
                {},
                self.paths.logs / "soc" / "sim-build.log",
                inputs=inputs,
                outputs=(simulator,),
            ),
            on=on,
        )
        return result, simulator
    def build(self, *, on: str = "local") -> object:
        """Generate and lint/elaborate the SoC through native Verilator."""

        generated = self.generate(on=on)
        if getattr(generated, "returncode", 0):
            return generated
        return self.native_verilator_lint(on=on)

    def simulate(self, *, on: str = "local") -> object:
        """Build selected CPU software, then build and run the native SoC simulator."""

        test = str(self.values.get("TEST_NAME", "smoke")).strip() or "smoke"
        self.dv.validate(test)
        generated = self.generate(on=on)
        if getattr(generated, "returncode", 0):
            return generated

        plan = self.resolve_plan()
        runtime_inputs: tuple[Path, ...] = ()

        software = self.software.build(test, on=on)
        if software is not None:
            if getattr(software, "returncode", 0):
                return software
            runtime_inputs = self.software.runtime_inputs(test)

        built, simulator = self.native_verilator_simulator(on=on)
        if getattr(built, "returncode", 0):
            return built

        from ...dv.func.functional import FunctionalFlow

        return FunctionalFlow(self.runner).run_systemverilog(
            top="soc",
            test_root=self.paths.tests,
            tb_dir=self.paths.tb,
            sim_dir=self.paths.sim,
            test_name=test,
            compiler="verilator",
            seed=int(self.values.get("SEED", "1")),
            executable=simulator,
            extra_inputs=runtime_inputs,
            wave_file=self.paths.sim / f"soc_tb_{test}.fst",
            log=self.paths.logs / "soc" / "sim.log",
            on=on,
        )

    def view(self, *, on: str = "local") -> object:
        """Open the waveform produced by the selected canonical SoC test."""

        from ...core.flow.session import WorkspaceFlow

        test = str(self.values.get("TEST_NAME", "smoke")).strip() or "smoke"
        wave = WorkspaceFlow._select_waveform(self.paths.sim, "soc", test)
        viewer = str(self.values.get("WAVE_VIEWER", "surfer"))
        env = WorkspaceFlow._viewer_environment(
            viewer, str(self.values.get("SURFER_BACKEND", "auto"))
        )
        print(f"[wave] test={test} {wave}", flush=True)
        return self.runner.run(
            CommandRequest(
                (viewer, str(wave)), wave.parent, env,
                self.paths.logs / "viewer" / "view.log", inputs=(wave,),
            ),
            on=on,
        )

    @staticmethod
    def write_json(path: Path, payload: dict[str, Any]) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return path.resolve()

    @staticmethod
    def read_filelists(ip_dir: Path) -> tuple[str, ...]:
        files = (ip_dir / "rtl" / "rtl_common.f", ip_dir / "rtl" / "rtl_ip.f")
        missing = [path for path in files if not path.is_file()]
        if missing:
            raise FileNotFoundError("missing canonical IP filelist(s): " + ", ".join(map(str, missing)))
        return tuple(
            line
            for flist in files
            for raw in flist.read_text(encoding="utf-8").splitlines()
            if (line := raw.strip()) and not line.startswith("#")
        )

    @staticmethod
    def merged_rtl_sources(ips: tuple[Path, ...]) -> tuple[str, ...]:
        merged: list[str] = []
        seen: set[str] = set()
        for ip in ips:
            for source in SocFlow.read_filelists(ip):
                if source not in seen:
                    seen.add(source)
                    merged.append(source)
        return tuple(merged)


    @staticmethod
    def _resolve_native_flist_entry(
        entry: str,
        *,
        release_root: Path,
        project_root: Path,
        run_root: Path,
    ) -> str:
        """Resolve one staged-release file-list entry without filesystem scanning."""

        directive = ""
        value = entry
        if entry.startswith("+incdir+"):
            directive = "+incdir+"
            value = entry[len(directive):]

        source = Path(value)
        if source.is_absolute():
            resolved = source
        else:
            candidates = (
                release_root / source,
                project_root / source,
                run_root / source,
            )
            resolved = next((candidate for candidate in candidates if candidate.exists()), None)
            if resolved is None:
                raise FileNotFoundError(
                    f"unresolved staged RTL entry {entry!r} from {release_root}"
                )

        resolved = resolved.resolve()
        try:
            rendered = resolved.relative_to(run_root.resolve()).as_posix()
        except ValueError:
            rendered = resolved.as_posix()
        return directive + rendered

    def resolve_soc_rtl_sources(self, plan: SoCPlan) -> RtlSourceSet:
        """Resolve FlexSoC-owned SoC RTL sources from explicit release contracts."""

        del plan
        entries: list[str] = []

        for release_root in self.loaded_ip_dirs():
            for entry in self.read_filelists(release_root):
                normalized = entry.replace("\\", "/")
                if (
                    "rtl/deps/flexsoc/prim_opentitan/" in normalized
                    or "rtl/deps/flexsoc/pkgs/" in normalized
                ):
                    continue
                entries.append(
                    self._resolve_native_flist_entry(
                        entry,
                        release_root=release_root,
                        project_root=self.context.project_root,
                        run_root=self.paths.run,
                    )
                )

        generated = (
            self.paths.rtl / "autogen" / "tl_main_pkg.sv",
            self.paths.rtl / "autogen" / "xbar_main.sv",
            self.paths.rtl / "soc.sv",
        )
        for source in generated:
            if not source.is_file():
                raise FileNotFoundError(
                    f"missing generated SoC RTL source required by native resolver: {source}"
                )
            entries.append(source.resolve().relative_to(self.paths.run.resolve()).as_posix())

        return RtlSourceSet.from_entries(entries)

    def write_soc_rtl_filelist(self, plan: SoCPlan) -> Path:
        """Write the native SoC-owned source manifest."""

        return self.resolve_soc_rtl_sources(plan).write(self.paths.rtl / "rtl_soc.f")



    def materialize_native_primitives(self) -> Path:
        """Build one native primitive library with deterministic ownership.

        FlexSoC-owned primitives win. Pinned lowRISC generic and concrete prim
        RTL only fill missing filenames, so Slang sees one implementation of
        each primitive instead of overlapping vendor/native libraries.
        """

        flexsoc_root = self.context.project_root / "hw" / "ips" / "prim_opentitan"
        vendor_root = self.context.project_root / "vendor" / "lowrisc_ip" / "ip" / "prim" / "rtl"
        generic_root = (
            self.context.project_root
            / "vendor"
            / "lowrisc_ip"
            / "ip"
            / "prim_generic"
            / "rtl"
        )
        if not flexsoc_root.is_dir():
            raise FileNotFoundError(
                f"missing FlexSoC primitive library required by native SoC flow: {flexsoc_root}"
            )
        if not generic_root.is_dir():
            raise FileNotFoundError(
                f"missing lowRISC generic primitive fallback required by native SoC flow: {generic_root}"
            )

        shutil.rmtree(self.paths.rtl / "prim_generic", ignore_errors=True)
        output_root = self.paths.rtl / "prim_native"
        shutil.rmtree(output_root, ignore_errors=True)
        output_root.mkdir(parents=True, exist_ok=True)

        count = 0
        for source in sorted(flexsoc_root.iterdir()):
            if not source.is_file() or source.suffix not in {".sv", ".svh"}:
                continue
            (output_root / source.name).write_text(
                source.read_text(encoding="utf-8"), encoding="utf-8"
            )
            count += 1

        for source in sorted(generic_root.glob("prim_generic_*.sv")):
            target = output_root / source.name.replace("prim_generic_", "prim_", 1)
            if target.exists():
                continue
            target.write_text(
                source.read_text(encoding="utf-8").replace("prim_generic_", "prim_"),
                encoding="utf-8",
            )
            count += 1

        if vendor_root.is_dir():
            for source in sorted(vendor_root.iterdir()):
                if (
                    not source.is_file()
                    or source.suffix not in {".sv", ".svh"}
                    or source.name.endswith("_pkg.sv")
                ):
                    continue
                target = output_root / source.name
                if target.exists():
                    continue
                target.write_text(source.read_text(encoding="utf-8"), encoding="utf-8")
                count += 1

        if count == 0:
            raise FileNotFoundError("native primitive library resolved no RTL sources")
        return output_root

    def materialize_native_packages(self) -> Path:
        """Materialize one package library, preferring FlexSoC-owned sources."""

        source_root = self.context.project_root / "hw" / "ips" / "pkgs"
        vendor_root = self.context.project_root / "vendor" / "lowrisc_ip" / "ip" / "prim" / "rtl"
        if not source_root.is_dir():
            raise FileNotFoundError(
                f"missing FlexSoC package library required by native SoC flow: {source_root}"
            )

        output_root = self.paths.rtl / "pkgs_native"
        shutil.rmtree(output_root, ignore_errors=True)
        output_root.mkdir(parents=True, exist_ok=True)

        count = 0
        for source in sorted(source_root.iterdir()):
            if not source.is_file() or source.suffix not in {".sv", ".svh"}:
                continue
            (output_root / source.name).write_text(
                source.read_text(encoding="utf-8"), encoding="utf-8"
            )
            count += 1

        if vendor_root.is_dir():
            for source in sorted(vendor_root.glob("*_pkg.sv")):
                target = output_root / source.name
                if target.exists():
                    continue
                target.write_text(source.read_text(encoding="utf-8"), encoding="utf-8")
                count += 1

        top_pkg = output_root / "top_pkg.sv"
        if not top_pkg.is_file():
            raise FileNotFoundError(
                f"FlexSoC native package library is missing required top_pkg.sv: {top_pkg}"
            )
        if count == 0:
            raise FileNotFoundError("native package library resolved no sources")
        return output_root
    def write_native_rtl_filelist(self, plan: SoCPlan, *, on: str = "local") -> Path:
        """Generate the complete tool-ready SoC RTL closure with Slang."""

        from types import SimpleNamespace

        top_file = self.paths.rtl / "soc.sv"
        ownership_file = self.paths.rtl / "rtl_soc.f"
        if not top_file.is_file():
            raise FileNotFoundError(f"missing generated SoC top: {top_file}")
        if not ownership_file.is_file():
            raise FileNotFoundError(f"missing native SoC ownership manifest: {ownership_file}")

        primitive_root = self.materialize_native_primitives()
        package_root = self.materialize_native_packages()

        lowrisc = self.context.project_root / "vendor" / "lowrisc_ip"
        if not lowrisc.is_dir():
            raise FileNotFoundError(
                f"missing pinned lowRISC IP vendor tree required by SoC RTL closure: {lowrisc}"
            )

        search_roots: list[Path] = [primitive_root, package_root]

        for relative in (
            Path("ip/tlul/rtl"),
            Path("ip/lc_ctrl/rtl"),
        ):
            candidate = lowrisc / relative
            if candidate.is_dir():
                search_roots.append(candidate)

        if plan.host == "ibex":
            ibex_rtl = self.context.project_root / "vendor" / "lowrisc_ibex" / "rtl"
            if not ibex_rtl.is_dir():
                raise FileNotFoundError(
                    f"missing pinned Ibex RTL root required by SoC RTL closure: {ibex_rtl}"
                )
            search_roots.insert(2, ibex_rtl)

        seed_files: list[Path] = []
        include_dirs: list[Path] = [package_root, primitive_root]
        for raw in ownership_file.read_text(encoding="utf-8").splitlines():
            entry = raw.strip()
            if not entry or entry.startswith("#"):
                continue
            if entry.startswith("+incdir+"):
                for item in entry[len("+incdir+"):].split("+"):
                    if not item:
                        continue
                    path = Path(item)
                    include_dirs.append(
                        path if path.is_absolute() else (self.paths.run / path).resolve()
                    )
                continue

            path = Path(entry)
            source = path if path.is_absolute() else (self.paths.run / path).resolve()
            if not source.is_file():
                raise FileNotFoundError(f"missing rtl_soc.f seed source: {source}")
            if source != top_file.resolve():
                seed_files.append(source)

        top_pkg = package_root / "top_pkg.sv"
        package_files = [top_pkg]
        package_files.extend(
            source
            for source in sorted(package_root.glob("*_pkg.sv"))
            if source != top_pkg
        )

        discovery_args: list[str] = []
        if plan.host == "ibex":
            discovery_args.append("-DSYNTHESIS")
        for directory in dict.fromkeys(include_dirs):
            discovery_args.extend(("-I", str(directory)))
        discovery_args.extend(str(source) for source in package_files)
        discovery_args.extend(str(source) for source in seed_files)

        output = self.paths.rtl / "rtl.f"
        RtlFlow.run_flist(
            SimpleNamespace(
                root=self.paths.run,
                search_root=search_roots,
                top_file=top_file,
                top="soc",
                extra_args=shlex.join(discovery_args),
                slang=str(self.values.get("SLANG", "slang")),
                output=output,
                common_out=None,
                ip_out=None,
                common_root=[],
                synthesis=False,
            ),
            runner=self.runner,
            on=on,
        )

        if not output.is_file() or not output.read_text(encoding="utf-8").strip():
            raise RuntimeError(f"Slang did not produce a usable SoC RTL filelist: {output}")

        raw_lines = [
            line
            for line in output.read_text(encoding="utf-8").splitlines()
            if line.strip() != "+define+SYNTHESIS"
        ]

        # Preserve directives first, then force canonical FlexSoC packages before
        # dependent RTL such as tlul_pkg.sv. Remaining Slang closure order follows.
        directives = [line for line in raw_lines if line.startswith("+")]
        package_entries = []
        for source in package_files:
            resolved = source.resolve()
            try:
                rendered = resolved.relative_to(self.paths.run.resolve()).as_posix()
            except ValueError:
                rendered = resolved.as_posix()
            package_entries.append(rendered)

        package_set = set(package_entries)
        body = [
            line
            for line in raw_lines
            if not line.startswith("+") and line not in package_set
        ]

        ordered: list[str] = []
        seen: set[str] = set()
        for line in (*directives, *package_entries, *body):
            if not line or line in seen:
                continue
            seen.add(line)
            ordered.append(line)

        output.write_text("\n".join(ordered) + "\n", encoding="utf-8")
        return output

    def find_sv_file(self, module_name: str) -> Path | None:
        """Resolve a loaded device only from its frozen staged release."""

        rtl = self.paths.run / "ips" / module_name / "rtl"
        if not rtl.is_dir():
            return None
        exact = rtl / f"{module_name}.sv"
        if exact.is_file():
            return exact
        matches = sorted(rtl.rglob(f"{module_name}.sv"))
        return matches[0] if len(matches) == 1 else None

    @staticmethod
    def parse_ports(sv_file: Path) -> list[tuple[str, str | None, str]]:
        content = sv_file.read_text(encoding="utf-8")
        content = re.sub(r"//.*?$|/\*.*?\*/", "", content, flags=re.DOTALL | re.MULTILINE)
        content = re.sub(r"\s+", " ", content)
        match = re.search(r"\bmodule\b.*?\((?P<plist>.*?)\)\s*;", content)
        if not match:
            return []
        ports = []
        for declaration in (part.strip() for part in match.group("plist").split(",")):
            parsed = re.match(r"^\s*(input|output)\b\s+(.*)$", declaration)
            if not parsed:
                continue
            direction, rest = parsed.group(1), parsed.group(2).strip()
            name_match = re.search(r"([A-Za-z_]\w*)\s*$", rest)
            if not name_match:
                continue
            ports.append((direction, rest[:name_match.start(1)].strip() or None, name_match.group(1)))
        return ports

    @staticmethod
    def collect_soc_ports(modules_ports: dict[str, list[tuple[str, str | None, str]]]) -> dict[str, str]:
        all_ports: dict[str, str] = {}
        for ports in modules_ports.values():
            for direction, dtype, name in ports:
                all_ports.setdefault(name, direction + " " + (dtype or ""))
        return all_ports

    @staticmethod
    def add_host_ports(host: str, all_ports: dict[str, str]) -> dict[str, str]:
        if host == "uart":
            all_ports.setdefault("cio_rx_i", "input logic")
            all_ports.setdefault("cio_tx_o", "output logic")
            all_ports.setdefault("cio_tx_en_o", "output logic")
        return all_ports

    @staticmethod
    def generate_port_decls(all_ports: dict[str, str]) -> list[str]:
        ports = [
            (name, direction)
            for name, direction in all_ports.items()
            if "tl_" not in name and name not in {"clk_i", "rst_ni"} and "intr" not in name
        ]
        return [
            f"  {direction} {name}{',' if index + 1 < len(ports) else ''}"
            for index, (name, direction) in enumerate(ports)
        ]

    @staticmethod
    def generate_module_inst(module: str, ports: list[tuple[str, str | None, str]]) -> str:
        from flexsoc.backend.core.render.templates import templates
        connections = [".clk_i", ".rst_ni", f".tl_i(tl_{module}_h2d)", f".tl_o(tl_{module}_d2h)"]
        connections.extend(
            f".{name}"
            for _direction, _dtype, name in ports
            if name not in {"tl_i", "tl_o", "clk_i", "rst_ni"}
            and not any(token in name for token in ("intr", "alert_rx", "alert_tx"))
        )
        connections.extend(
            f".{name}()"
            for _direction, _dtype, name in ports
            if any(token in name for token in ("intr", "alert_rx", "alert_tx"))
        )
        return templates.render("design/soc/module_instance.sv.j2", module=module, connections=connections)

    @staticmethod
    def defaults(plan: SoCPlan) -> str:
        from flexsoc.backend.core.render.templates import templates

        values: dict[str, object] = {}
        if plan.host == "ibex":
            sram = plan.device("sram")
            values.update(
                mem_size=sram.size,
                boot_addr=f"32'h{plan.ibex_boot_addr:08X}",
            )
        return templates.render(f"design/soc/defaults_{plan.host}.sv.j2", **values)

    @staticmethod
    def render_xbar_connections(plan: SoCPlan) -> str:
        from flexsoc.backend.core.render.templates import templates
        connections: list[str] = []
        if plan.host == "ibex":
            connections.extend((
                ".tl_ibex_i (tl_ibex_h2d)", ".tl_ibex_o (tl_ibex_d2h)",
                ".tl_sram_o (tl_sram_h2d)", ".tl_sram_i (tl_sram_d2h)",
            ))
        elif plan.host == "uart":
            connections.extend((
                ".tl_uart_host_i (tl_uart_host_h2d)", ".tl_uart_host_o (tl_uart_host_d2h)",
            ))
        for device in plan.external_devices:
            connections.extend((
                f".tl_{device.name}_o (tl_{device.name}_h2d)",
                f".tl_{device.name}_i (tl_{device.name}_d2h)",
            ))
        return templates.render("design/soc/xbar.sv.j2", connections=connections)

    def module_ports(self, plan: SoCPlan) -> dict[str, list[tuple[str, str | None, str]]]:
        parsed = {}
        for device in plan.external_devices:
            source = self.find_sv_file(device.name)
            if source is None:
                raise FileNotFoundError(
                    f"loaded SoC device {device.name!r} has no unique rtl/{device.name}.sv"
                )
            parsed[device.name] = self.parse_ports(source)
        return parsed

    def render_soc_sv(self, plan: SoCPlan, modules_ports: dict[str, list[tuple[str, str | None, str]]]) -> str:
        from flexsoc.backend.core.render.templates import templates
        all_ports = self.add_host_ports(plan.host, self.collect_soc_ports(modules_ports))
        port_declarations = "\n".join(self.generate_port_decls(all_ports))
        tl_signals = "\n".join(
            line
            for module in modules_ports
            for line in (
                f"  tlul_pkg::tl_h2d_t tl_{module}_h2d;",
                f"  tlul_pkg::tl_d2h_t tl_{module}_d2h;",
            )
        )
        if tl_signals:
            tl_signals += "\n"
        instances = "\n".join(
            self.generate_module_inst(module, ports) for module, ports in modules_ports.items()
        )
        return templates.render(
            "design/soc/soc.sv.j2",
            port_declarations=port_declarations,
            defaults=self.defaults(plan),
            tl_signals=tl_signals,
            xbar=self.render_xbar_connections(plan),
            module_instances=instances,
        )

    @staticmethod
    def write_soc_core(path: Path, plan: SoCPlan) -> Path:
        from flexsoc.backend.core.render.templates import templates
        return templates.write(
            "design/soc/soc.core.j2", path, force=True,
            host=plan.host, modules=[device.name for device in plan.external_devices],
            merge_key="<<: *default_target",
        )

    def generate_top(self, plan: SoCPlan) -> Path:
        modules_ports = self.module_ports(plan)
        all_ports = self.add_host_ports(plan.host, self.collect_soc_ports(modules_ports))
        output = self.paths.rtl / "soc.sv"
        output.write_text(self.render_soc_sv(plan, modules_ports), encoding="utf-8")
        self.dv.generate(plan)
        self.software.generate_memory_map(plan)
        self.write_soc_core(self.paths.run / "soc.core", plan)
        return output
