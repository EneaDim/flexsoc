"""Compatibility with a *published slang serialization*, not hand-picked mock shape.

This excerpt retains the compiler-generated addr / internalSymbol / duplicated
Port+Variable pairs, BinaryOp and ContinuousAssign from Ming Yang's 2024
published slang AST for `module adder`, see:
https://threelambda.com/en/2024/07/18/2024-7-18-slang-ast-hier-tree/
It was shortened to the `design` subtree; not generated by compiling locally.
"""
from pathlib import Path
import json

from flexsoc.backend.dv.rtl_viewer import RtlDesign


FIXTURE = Path(__file__).with_name('fixtures') / 'published_slang_adder_excerpt.json'


def test_published_slang_ast_preserves_ports_and_expression_edges(tmp_path):
    payload = json.loads(FIXTURE.read_text())
    design = RtlDesign(payload, root=tmp_path, top='adder')
    graph = design.diagram()
    nodes = {node['name']: node for node in graph['nodes']}
    assert set(nodes) == {'a', 'b', 'sum', 'Add'}
    assert all(nodes[k]['type'] == 'port' for k in ('a', 'b', 'sum'))
    assert nodes['Add']['type'] == 'operator'
    assert (nodes['a']['direction'], nodes['b']['direction'], nodes['sum']['direction']) == ('in', 'in', 'out')
    assert { (e['source'], e['target']) for e in graph['edges']} == {
        ('/::sig:a', '/::op:0'), ('/::sig:b', '/::op:0'), ('/::op:0', '/::sig:sum')}
    assert design.cone('/', '/::sig:a', '/::sig:sum')['status'] == 'resolved'


def test_slang_address_relocation_does_not_change_revision(tmp_path):
    payload = json.loads(FIXTURE.read_text())
    before = RtlDesign(payload, root=tmp_path, top='adder').revision
    payload['design']['members'][1]['body']['members'][6]['assignment']['right']['left']['symbol'] = '901901 a'
    payload['design']['members'][1]['addr'] = 999
    assert RtlDesign(payload, root=tmp_path, top='adder').revision == before
