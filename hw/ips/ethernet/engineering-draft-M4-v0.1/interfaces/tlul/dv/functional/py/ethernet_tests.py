"""Editable source for FlexSoC CSR vector generation (post fx regmap_py).

Only CSR tests are currently runnable; packet tests require the real packet top.
The independent preview generator `scripts/generate_vectors.py` consumes the
same canonical `scenarios.py` and the actual user-generated reg package.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import scenarios
import ethernet_regmap as regmap  # GENERATED by fx regmap_py; never hand-author this module

TESTS = tuple(case.name for case in scenarios.CSR_SCENARIOS)


def hx(x: int) -> str:
    return f'0x{x & 0xffffffff:08x}'


def vectors(case: scenarios.CsrScenario) -> tuple[list[str], list[str]]:
    ins, outs = [], []
    for op in case.operations:
        register = getattr(regmap.PRIMARY, op.register)
        if op.kind == 'write':
            ins.append(f'{op.cycle} @write {register.path} {hx(op.value)}')
        elif op.kind == 'read':
            # Stream-mode FlexSoC TBs execute CSR @read via their input driver.
            # Both SV and cocotb check the returned bus data in expect_reg().
            ins.append(f'{op.cycle} @read {register.path} {hx(op.value)} {hx(op.mask if op.mask is not None else 0xffffffff)}')
        else:
            raise ValueError(f'unknown operation: {op.kind}')
    return ins, outs


def write_test(root: str | Path, case: scenarios.CsrScenario) -> None:
    folder = Path(root) / case.name
    folder.mkdir(parents=True, exist_ok=True)
    regmap.write_config(folder / 'config.regs', [])
    ins, outs = vectors(case)
    (folder / 'data_in.vec').write_text('# Generated from functional/py/scenarios.py; CSR-only\n' + ('\n'.join(ins) + '\n' if ins else ''), encoding='utf8')
    (folder / 'data_out.vec').write_text('# Generated from functional/py/scenarios.py; CSR-only\n' + ('\n'.join(outs) + '\n' if outs else ''), encoding='utf8')


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--tests-dir', default='../tests')
    parser.add_argument('--test', action='append', default=[])
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        print('\n'.join(TESTS))
        return 0
    unknown = set(args.test) - set(TESTS)
    if unknown:
        raise ValueError(f'unknown Ethernet test(s): {sorted(unknown)}')
    for case in scenarios.CSR_SCENARIOS:
        if not args.test or case.name in args.test:
            write_test(args.tests_dir, case)
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
