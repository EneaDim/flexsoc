#!/usr/bin/env python3
"""
Generate compact CSV vector files specifically meant for the SystemVerilog
testbench.

The files generated by this script are intentionally simple:
- only signed integer fixed-point values are emitted
- one vector per row
- a small header is included for readability
- parsing from SystemVerilog can be done with a single $sscanf()

CSV columns:
    mode,x_in,y_in,z_in,x_exp,y_exp,z_exp

Mode encoding:
    0 = rotation
    1 = vectoring
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

from cordic_model import (
    CordicConfig,
    FixedFormat,
    generate_directed_rotation_vectors,
    generate_directed_vectoring_vectors,
    generate_random_rotation_vectors,
    generate_random_vectoring_vectors,
)


def write_sv_csv(path: Path, vectors) -> None:
    """
    Write a simplified CSV format for direct SystemVerilog consumption.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["mode", "x_in", "y_in", "z_in", "x_exp", "y_exp", "z_exp"])

        for vec in vectors:
            mode = 0 if vec.mode == "rotation" else 1
            writer.writerow([
                mode,
                vec.x_in_fixed,
                vec.y_in_fixed,
                vec.z_in_fixed,
                vec.x_out_fixed,
                vec.y_out_fixed,
                vec.z_out_fixed,
            ])


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate compact SV-friendly CORDIC vector CSVs")

    parser.add_argument("--width", type=int, default=16, help="Data path width")
    parser.add_argument("--frac", type=int, default=14, help="Data path fractional bits")
    parser.add_argument("--angle-width", type=int, default=16, help="Angle path width")
    parser.add_argument("--angle-frac", type=int, default=13, help="Angle path fractional bits")
    parser.add_argument("--iterations", type=int, default=16, help="Number of CORDIC iterations")
    parser.add_argument("--guard-bits", type=int, default=3, help="Internal guard bits")
    parser.add_argument("--wrap-output", action="store_true", help="Wrap outputs instead of saturating them")

    parser.add_argument(
        "--out-dir",
        type=str,
        default="workspace/runs/cordic/dev/sim/vectors",
        help="Directory where CSV files are written",
    )
    parser.add_argument("--random-count", type=int, default=64, help="Number of random vectors per mode")
    parser.add_argument("--seed", type=int, default=1234, help="Random seed")

    args = parser.parse_args()

    cfg = CordicConfig(
        data_format=FixedFormat(width=args.width, frac=args.frac, signed=True),
        angle_format=FixedFormat(width=args.angle_width, frac=args.angle_frac, signed=True),
        iterations=args.iterations,
        compensate_gain=True,
        internal_guard_bits=args.guard_bits,
        saturate_output=not args.wrap_output,
    )

    out_dir = Path(args.out_dir)

    rot_dir = generate_directed_rotation_vectors(cfg)
    vec_dir = generate_directed_vectoring_vectors(cfg)
    rot_rnd = generate_random_rotation_vectors(cfg, args.random_count, args.seed)
    vec_rnd = generate_random_vectoring_vectors(cfg, args.random_count, args.seed)

    write_sv_csv(out_dir / "cordic_rotation_directed_sv.csv", rot_dir)
    write_sv_csv(out_dir / "cordic_vectoring_directed_sv.csv", vec_dir)
    write_sv_csv(out_dir / "cordic_rotation_random_sv.csv", rot_rnd)
    write_sv_csv(out_dir / "cordic_vectoring_random_sv.csv", vec_rnd)

    print(f"Generated SV vector CSVs in: {out_dir}")


if __name__ == "__main__":
    main()
