def build_argparser() -> argparse.ArgumentParser:
    """
    Build the command-line parser.

    The interface is kept intentionally simple so that the script can be used:
    - manually during development
    - from Makefiles
    - inside CI or regression scripts
    """
    parser = argparse.ArgumentParser(description="CORDIC plotting utilities")

    parser.add_argument("--width", type=int, default=16, help="Data path width")
    parser.add_argument("--frac", type=int, default=14, help="Data path fractional bits")
    parser.add_argument("--angle-width", type=int, default=16, help="Angle path width")
    parser.add_argument("--angle-frac", type=int, default=13, help="Angle path fractional bits")
    parser.add_argument("--iterations", type=int, default=16, help="Number of CORDIC iterations")
    parser.add_argument("--guard-bits", type=int, default=3, help="Internal x/y guard bits")
    parser.add_argument(
        "--wrap-output",
        action="store_true",
        help="Wrap x/y outputs instead of saturating them",
    )

    parser.add_argument(
        "--output-dir",
        type=str,
        default="workspace/runs/cordic/dev/report/plots",
        help="Directory where PNG plots will be saved",
    )

    parser.add_argument(
        "--num-points",
        type=int,
        default=2001,
        help="Number of sweep points for each analysis",
    )

    parser.add_argument(
        "--radius",
        type=float,
        default=0.8,
        help="Radius used for vectoring circular sweep",
    )

    parser.add_argument(
        "--rotation-only",
        action="store_true",
        help="Generate only rotation-mode plots",
    )

    parser.add_argument(
        "--vectoring-only",
        action="store_true",
        help="Generate only vectoring-mode plots",
    )

    return parser


def main() -> None:
    """
    Main CLI entry point.
    """
    args = build_argparser().parse_args()

    cfg = CordicConfig(
        data_format=FixedFormat(width=args.width, frac=args.frac, signed=True),
        angle_format=FixedFormat(width=args.angle_width, frac=args.angle_frac, signed=True),
        iterations=args.iterations,
        compensate_gain=True,
        internal_guard_bits=args.guard_bits,
        saturate_output=not args.wrap_output,
    )

    print("CORDIC plotting configuration")
    print("-----------------------------")
    print(f"Data width      : {cfg.data_format.width}")
    print(f"Data frac       : {cfg.data_format.frac}")
    print(f"Angle width     : {cfg.angle_format.width}")
    print(f"Angle frac      : {cfg.angle_format.frac}")
    print(f"Iterations      : {cfg.iterations}")
    print(f"Output dir      : {args.output_dir}")
    print(f"Sweep points    : {args.num_points}")
    print(f"Vector radius   : {args.radius}")
    print()

    if not args.vectoring_only:
        run_rotation_plots(cfg, args.output_dir, args.num_points)

    if not args.rotation_only:
        run_vectoring_plots(cfg, args.output_dir, args.num_points, args.radius)


if __name__ == "__main__":
    main()
