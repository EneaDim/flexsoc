# =============================================================================
# Top-level runners
# =============================================================================

def run_rotation_plots(cfg: CordicConfig, output_dir: str, num_points: int) -> None:
    """
    Generate all rotation-mode plots and print an error summary.
    """
    print("Generating rotation-mode plots...")
    data = build_rotation_sweep(cfg, num_points=num_points)

    print_error_summary("Rotation cosine error", data.cos_err)
    print_error_summary("Rotation sine error", data.sin_err)

    plot_rotation_waveforms(data, output_dir)
    plot_rotation_errors(data, output_dir)
    plot_rotation_histograms(data, output_dir)


def run_vectoring_plots(cfg: CordicConfig, output_dir: str, num_points: int, radius: float) -> None:
    """
    Generate all vectoring-mode plots and print an error summary.
    """
    print("Generating vectoring-mode plots...")
    data = build_vectoring_sweep(cfg, radius=radius, num_points=num_points)

    print_error_summary("Vectoring magnitude error", data.mag_err)
    print_error_summary("Vectoring angle error", data.ang_err)

    plot_vectoring_xy_path(data, output_dir)
    plot_vectoring_waveforms(data, output_dir)
    plot_vectoring_errors(data, output_dir)
    plot_vectoring_histograms(data, output_dir)


