#!/usr/bin/env python3
"""
CORDIC plotting and analysis utilities.

This module is intended to complement the CORDIC reference model by providing
high-quality visual inspection of:
- sine/cosine estimation quality in rotation mode
- magnitude/angle estimation quality in vectoring mode
- absolute error trends over the input domain
- error histograms for quick regression inspection

The plots generated by this script are particularly useful during:
- early algorithm bring-up
- RTL vs model alignment
- fixed-point format selection
- iteration count tradeoff studies
- regression result review

This file deliberately imports the golden model from cordic_model.py so that
all numerical behavior remains centralized in the same reference implementation.
"""

from __future__ import annotations

import argparse
import math
import os
from dataclasses import dataclass

import matplotlib.pyplot as plt
import numpy as np

from cordic_model import (
    PI,
    CordicConfig,
    FixedFormat,
    atan2_mag_fixed,
    atan2_math_reference,
    fixed_to_float,
    normalize_angle_pm_pi,
    sincos_fixed,
    sincos_math_reference,
)


# =============================================================================
# Dataclasses used to keep plotting data organized
# =============================================================================

@dataclass
class RotationSweepData:
    """
    Container for rotation-mode sweep results.

    Attributes
    ----------
    angles:
        Input angles in radians.
    cos_ref:
        Reference cosine values from Python math library.
    sin_ref:
        Reference sine values from Python math library.
    cos_dut:
        CORDIC fixed-point cosine converted back to float.
    sin_dut:
        CORDIC fixed-point sine converted back to float.
    cos_err:
        Absolute cosine error.
    sin_err:
        Absolute sine error.
    """
    angles: np.ndarray
    cos_ref: np.ndarray
    sin_ref: np.ndarray
    cos_dut: np.ndarray
    sin_dut: np.ndarray
    cos_err: np.ndarray
    sin_err: np.ndarray


@dataclass
class VectoringSweepData:
    """
    Container for vectoring-mode sweep results.

    Attributes
    ----------
    angles:
        Sweep angle used to generate the Cartesian input points.
    x:
        Generated x Cartesian coordinates.
    y:
        Generated y Cartesian coordinates.
    mag_ref:
        Reference magnitude values.
    ang_ref:
        Reference atan2 values.
    mag_dut:
        CORDIC magnitude estimate.
    ang_dut:
        CORDIC angle estimate.
    mag_err:
        Absolute magnitude error.
    ang_err:
        Absolute wrapped angular error.
    """
    angles: np.ndarray
    x: np.ndarray
    y: np.ndarray
    mag_ref: np.ndarray
    ang_ref: np.ndarray
    mag_dut: np.ndarray
    ang_dut: np.ndarray
    mag_err: np.ndarray
    ang_err: np.ndarray


# =============================================================================
# Utility helpers
# =============================================================================

def ensure_dir(path: str) -> None:
    """
    Create the target directory if it does not already exist.
    """
    os.makedirs(path, exist_ok=True)


def save_figure(output_dir: str, filename: str) -> None:
    """
    Save the current matplotlib figure using a consistent configuration.

    Parameters
    ----------
    output_dir:
        Directory where the figure will be written.
    filename:
        Output PNG filename.
    """
    ensure_dir(output_dir)
    full_path = os.path.join(output_dir, filename)
    plt.tight_layout()
    plt.savefig(full_path, dpi=180, bbox_inches="tight")
    print(f"Saved plot: {full_path}")


def print_error_summary(name: str, values: np.ndarray) -> None:
    """
    Print a compact numerical summary of an error array.

    Parameters
    ----------
    name:
        Human-readable metric name.
    values:
        NumPy array of error values.
    """
    print(
        f"{name:<24} "
        f"min={np.min(values):.6e}  "
        f"mean={np.mean(values):.6e}  "
        f"max={np.max(values):.6e}  "
        f"std={np.std(values):.6e}"
    )


# =============================================================================
# Data generation for plotting
# =============================================================================

def build_rotation_sweep(cfg: CordicConfig, num_points: int = 2001) -> RotationSweepData:
    """
    Sweep the full angle interval [-pi, pi] and compare CORDIC vs reference.

    This is the most useful plot set for evaluating:
    - trigonometric approximation quality
    - angle-domain regions with larger error
    - impact of fixed-point quantization
    - impact of iteration count

    Parameters
    ----------
    cfg:
        CORDIC configuration.
    num_points:
        Number of sample points across the angle domain.

    Returns
    -------
    RotationSweepData
        Structured sweep results.
    """
    angles = np.linspace(-PI, PI, num_points)

    cos_ref = np.zeros_like(angles)
    sin_ref = np.zeros_like(angles)
    cos_dut = np.zeros_like(angles)
    sin_dut = np.zeros_like(angles)

    for idx, angle in enumerate(angles):
        # Reference values from the Python math library.
        c_ref, s_ref = sincos_math_reference(angle)
        cos_ref[idx] = c_ref
        sin_ref[idx] = s_ref

        # Fixed-point CORDIC output converted back to float.
        dut = sincos_fixed(angle, cfg)
        cos_dut[idx] = fixed_to_float(dut.x, cfg.data_format)
        sin_dut[idx] = fixed_to_float(dut.y, cfg.data_format)

    cos_err = np.abs(cos_ref - cos_dut)
    sin_err = np.abs(sin_ref - sin_dut)

    return RotationSweepData(
        angles=angles,
        cos_ref=cos_ref,
        sin_ref=sin_ref,
        cos_dut=cos_dut,
        sin_dut=sin_dut,
        cos_err=cos_err,
        sin_err=sin_err,
    )


def build_vectoring_sweep(
    cfg: CordicConfig,
    radius: float = 0.8,
    num_points: int = 2001,
) -> VectoringSweepData:
    """
    Sweep a circle in Cartesian space and compare vectoring-mode outputs.

    The sweep creates points:
        x = r * cos(theta)
        y = r * sin(theta)

    This is a clean and very informative way to evaluate:
    - angle estimation error across quadrants
    - magnitude estimation consistency
    - corner behavior around axes
    - phase discontinuity handling around +/- pi

    Parameters
    ----------
    cfg:
        CORDIC configuration.
    radius:
        Radius of the swept circle. It should stay well inside the supported
        fixed-point dynamic range to avoid intermediate overflow.
    num_points:
        Number of points along the circle.

    Returns
    -------
    VectoringSweepData
        Structured sweep results.
    """
    angles = np.linspace(-PI, PI, num_points)

    x = radius * np.cos(angles)
    y = radius * np.sin(angles)

    mag_ref = np.zeros_like(angles)
    ang_ref = np.zeros_like(angles)
    mag_dut = np.zeros_like(angles)
    ang_dut = np.zeros_like(angles)

    for idx, (x_val, y_val) in enumerate(zip(x, y)):
        # Exact mathematical reference.
        mag_r, ang_r = atan2_math_reference(float(x_val), float(y_val))
        mag_ref[idx] = mag_r
        ang_ref[idx] = ang_r

        # Fixed-point CORDIC estimate converted back to float.
        dut = atan2_mag_fixed(float(x_val), float(y_val), cfg)
        mag_dut[idx] = dut.x
        ang_dut[idx] = dut.z

    mag_err = np.abs(mag_ref - mag_dut)

    # Angle error must be wrapped because phase is periodic.
    ang_err = np.array(
        [abs(normalize_angle_pm_pi(ref - dut)) for ref, dut in zip(ang_ref, ang_dut)]
    )

    return VectoringSweepData(
        angles=angles,
        x=x,
        y=y,
        mag_ref=mag_ref,
        ang_ref=ang_ref,
        mag_dut=mag_dut,
        ang_dut=ang_dut,
        mag_err=mag_err,
        ang_err=ang_err,
    )


# =============================================================================
# Plotting functions for rotation mode
# =============================================================================

def plot_rotation_waveforms(data: RotationSweepData, output_dir: str) -> None:
    """
    Plot reference and CORDIC cosine on the same figure, then reference and
    CORDIC sine on another figure.

    Separate figures are used intentionally so each plot remains readable and
    publication-friendly.
    """
    plt.figure(figsize=(10, 5))
    plt.plot(data.angles, data.cos_ref, label="cos reference")
    plt.plot(data.angles, data.cos_dut, label="cos cordic")
    plt.xlabel("Angle [rad]")
    plt.ylabel("Cosine")
    plt.title("CORDIC rotation mode - cosine")
    plt.grid(True, alpha=0.3)
    plt.legend()
    save_figure(output_dir, "rotation_cosine.png")
    plt.close()

    plt.figure(figsize=(10, 5))
    plt.plot(data.angles, data.sin_ref, label="sin reference")
    plt.plot(data.angles, data.sin_dut, label="sin cordic")
    plt.xlabel("Angle [rad]")
    plt.ylabel("Sine")
    plt.title("CORDIC rotation mode - sine")
    plt.grid(True, alpha=0.3)
    plt.legend()
    save_figure(output_dir, "rotation_sine.png")
    plt.close()


def plot_rotation_errors(data: RotationSweepData, output_dir: str) -> None:
    """
    Plot absolute cosine and sine error versus angle.
    """
    plt.figure(figsize=(10, 5))
    plt.plot(data.angles, data.cos_err)
    plt.xlabel("Angle [rad]")
    plt.ylabel("Absolute error")
    plt.title("CORDIC rotation mode - absolute cosine error")
    plt.grid(True, alpha=0.3)
    save_figure(output_dir, "rotation_cosine_error.png")
    plt.close()

    plt.figure(figsize=(10, 5))
    plt.plot(data.angles, data.sin_err)
    plt.xlabel("Angle [rad]")
    plt.ylabel("Absolute error")
    plt.title("CORDIC rotation mode - absolute sine error")
    plt.grid(True, alpha=0.3)
    save_figure(output_dir, "rotation_sine_error.png")
    plt.close()


def plot_rotation_histograms(data: RotationSweepData, output_dir: str, bins: int = 80) -> None:
    """
    Plot histograms of cosine and sine absolute error.

    Histograms are useful to understand whether the implementation shows:
    - a narrow and well-controlled error distribution
    - long tails
    - outliers near specific regions of the input domain
    """
    plt.figure(figsize=(8, 5))
    plt.hist(data.cos_err, bins=bins)
    plt.xlabel("Absolute error")
    plt.ylabel("Count")
    plt.title("CORDIC rotation mode - cosine error histogram")
    plt.grid(True, alpha=0.3)
    save_figure(output_dir, "rotation_cosine_error_hist.png")
    plt.close()

    plt.figure(figsize=(8, 5))
    plt.hist(data.sin_err, bins=bins)
    plt.xlabel("Absolute error")
    plt.ylabel("Count")
    plt.title("CORDIC rotation mode - sine error histogram")
    plt.grid(True, alpha=0.3)
    save_figure(output_dir, "rotation_sine_error_hist.png")
    plt.close()


