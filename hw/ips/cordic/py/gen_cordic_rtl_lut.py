#!/usr/bin/env python3
"""
Generate a SystemVerilog package containing the fixed-point CORDIC angle LUT.

The package is meant to be the single RTL-side source of truth for:
- atan(2^-i) LUT entries
- pi and pi/2 fixed-point constants

The numerical format is taken from the same Python reference model used for:
- fixed-point conversion
- self-checks
- vector generation
- dashboard / plotting

This keeps the RTL constants bit-accurate with the model.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

from cordic_model import FixedFormat, float_to_fixed


def sv_signed_literal(width: int, value: int) -> str:
    """
    Convert a signed integer into a SystemVerilog signed literal.
    """
    return f"{width}'sd{value}"


def generate_pkg_text(
    package_name: str,
    angle_width: int,
    angle_frac: int,
    iterations: int,
) -> str:
    """
    Build the full SystemVerilog package text.
    """
    angle_fmt = FixedFormat(width=angle_width, frac=angle_frac, signed=True)

    pi_q = float_to_fixed(math.pi, angle_fmt)
    half_pi_q = float_to_fixed(math.pi / 2.0, angle_fmt)
    lut = [float_to_fixed(math.atan(2.0 ** (-i)), angle_fmt) for i in range(iterations)]

    lut_entries = ",\n".join(
        f"    {sv_signed_literal(angle_width, val)}" for val in lut
    )

    text = f"""// -----------------------------------------------------------------------------
// Auto-generated CORDIC LUT package
// -----------------------------------------------------------------------------
// Generated by:
//   py/gen_cordic_rtl_lut.py
//
// Do not edit manually.
// -----------------------------------------------------------------------------

package {package_name};

  // Signed fixed-point angle constants in Q format with:
  //   width = {angle_width}
  //   frac  = {angle_frac}
  localparam logic signed [{angle_width-1}:0] PI_Q      = {sv_signed_literal(angle_width, pi_q)};
  localparam logic signed [{angle_width-1}:0] HALF_PI_Q = {sv_signed_literal(angle_width, half_pi_q)};

  // atan(2^-i) lookup table
  localparam logic signed [{angle_width-1}:0] AtanLut [0:{iterations-1}] = '{{
{lut_entries}
  }};

endpackage
"""
    return text


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate RTL CORDIC LUT package")
    parser.add_argument(
        "--output",
        type=str,
        default="workspace/runs/cordic/dev/rtl/cordic_lut_pkg.sv",
        help="Output SystemVerilog package path",
    )
    parser.add_argument(
        "--package-name",
        type=str,
        default="cordic_lut_pkg",
        help="SystemVerilog package name",
    )
    parser.add_argument("--angle-width", type=int, default=16, help="Angle path width")
    parser.add_argument("--angle-frac", type=int, default=13, help="Angle fractional bits")
    parser.add_argument("--iterations", type=int, default=16, help="Number of LUT entries")

    args = parser.parse_args()

    pkg_text = generate_pkg_text(
        package_name=args.package_name,
        angle_width=args.angle_width,
        angle_frac=args.angle_frac,
        iterations=args.iterations,
    )

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(pkg_text)

    print(f"Generated: {output_path}")


if __name__ == "__main__":
    main()
